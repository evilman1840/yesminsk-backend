/**
 * Стоп-слова о митингах, акциях протеста и политике (см. Соглашение, разделы 3 и 5).
 * ban — однозначные: автор сразу в бан, сходка скрыта, решение за администратором в боте.
 * review — если понадобятся слова «только сообщить»: ничего не скрываем, пишем администратору (сейчас список пуст).
 * Текст сначала приводится к одному виду: регистр, ё → е, белорусские буквы, латиница-двойник, «м.и.т.и.н.г»
 */

export type StopLevel = 'ban' | 'review';
export interface StopHit {
  level: StopLevel;
  matches: string[]; // что нашли — показываем администратору
}

// Левая граница слова: перед стеблем не буква и не цифра
const L = '(?<![а-яa-z0-9])';

const BAN: string[] = [
  // Массовые мероприятия
  'митинг', 'пикет', 'протест(?!ир|ант)', 'забастов', 'стачк', 'шестви', 'майдан',
  'несанкционир', 'акци[а-я]*\\s+(?:протест|солидарн|памяти|против|в\\s+поддержку)',
  'марш[а-я]*\\s+(?:свобод|мира|несоглас|солидарн|женщин|пенсионер|за\\s|против)',
  'день\\s+воли',
  // Двусмысленные поводы (из Соглашения)
  'в\\s+знак\\s+(?:поддержк|протест|солидарн|несоглас|памяти)',
  'выраз[а-я]*\\s+(?:сво[а-я]+\\s+|наш[а-я]+\\s+)?(?:мнени|позици|несоглас|протест|недовольств)',
  'прогулк[а-я]*\\s+(?:против|за\\s+(?:свобод|перемен|справедлив|правд|бел))',
  'за\\s+свобод(?:у|ы)(?![а-я])',
  // Символика
  'бчб', 'бело-?красно-?бел', 'красно-?бело-?красн', 'пагон[яеи]', 'жыве', 'живе\\s+бел', 'слава\\s+украин',
  // Политика и персоналии
  'оппозиц', 'политзаключ', 'политзэк', 'политузник', 'политвязн', 'палитвязн', 'змагар', 'киберпартизан', 'кибер-партизан',
  'лукашенк', 'тихановск', 'бабарик', 'цепкал', 'латушк', 'статкевич', 'навальн',
  '(?:свободн|честн)[а-я]*\\s+выбор(?:ы|ов|ах|ам)(?![а-я])', 'фальсифик[а-я]*\\s+выбор', 'запрещенн[а-я]*\\s+символ',
  // Политический подтекст, символика, призывы на улицу
  'политик', 'политич', 'выбор(?:ы|ов|ах|ам)(?![а-я])', 'революц', 'демонстрац', 'флешмоб', 'марш(?!рут|ал|ир|мел|-брос)',
  'флаг(?!ман)', 'плакат', 'транспарант', 'лозунг', 'символик', 'ленточк',
  '(?:в|во)\\s+(?:белом|красном|бело-?красн)', 'дресс-?код', 'массов[а-я]*\\s+(?:собрани|мероприят|акци|выход)',
  'санкци', 'петици', 'сбор[а-я]*\\s+подпис', 'экстремист', 'автозак', 'омон(?:а|у|ом|е|ы|ов)?(?![а-я])', 'силовик', 'задержан',
  '(?:выходим|выйдем|выходите|все)\\s+на\\s+улиц', 'дзяды', 'куропат', 'бнр(?![а-я])', 'ждем\\s+перемен', 'путин(?![а-я])', 'зеленск'
];

// Сюда — слова, за которые не баним, а только пишем администратору
const REVIEW: string[] = [];

const banRe = BAN.map((p) => new RegExp(L + p, 'g'));
const reviewRe = REVIEW.map((p) => new RegExp(L + p, 'g'));

// Латиница и цифры, похожие на кириллицу: «митинr», «пр0тест»
const LOOKALIKE: Record<string, string> = { a: 'а', e: 'е', o: 'о', p: 'р', c: 'с', x: 'х', y: 'у', k: 'к', m: 'м', t: 'т', h: 'н', '0': 'о', '3': 'з' };

export function normalizeForStopWords(text: string): string {
  let s = text.toLowerCase().replace(/ё/g, 'е').replace(/і/g, 'и').replace(/ў/g, 'у');
  // Двойники меняем только внутри слов, где есть кириллица, чтобы не портить числа и ссылки
  s = s.replace(/[а-яa-z0-9]+/g, (w) => (/[а-я]/.test(w) ? w.replace(/[aeopcxykmth03]/g, (ch) => LOOKALIKE[ch]) : w));
  // «м.и.т.и.н.г», «м_и_т_и_н_г», «м и т и н г» → «митинг»
  s = s.replace(/(?<=[а-я])[.\_*·•]+(?=[а-я])/g, '');
  s = s.replace(/(?<![а-я])(?:[а-я][\s.\-_*]){2,}[а-я](?![а-я])/g, (w) => w.replace(/[\s.\-_*]/g, ''));
  // Отрицание вместе со списком после него: «без политики, символики и флагов» — это не нарушение
  s = s.replace(/(?<![а-я])(?:без|никак[а-я]*|не\s+(?:про|о|об|будет)|вне)\s+[«"]?[а-я]+(?:\s*(?:,|\sи\s|\sили\s)\s*[«"]?[а-я]+)*/g, ' ');
  return s.replace(/\s+/g, ' ');
}

const findAll = (s: string, list: RegExp[]) => {
  const found = new Set<string>();
  for (const re of list) for (const m of s.matchAll(re)) found.add(m[0].trim());
  return [...found];
};

/**
 * Проверка текстов сходки, анкеты или сообщения. null — всё чисто
 */
export function checkStopWords(...texts: Array<string | undefined | null>): StopHit | null {
  const s = normalizeForStopWords(texts.filter(Boolean).join('\n'));
  if (!s.trim()) return null;
  const ban = findAll(s, banRe);
  if (ban.length) return { level: 'ban', matches: ban };
  const review = findAll(s, reviewRe);
  return review.length ? { level: 'review', matches: review } : null;
}

// Тексты из доп. полей шаблона (фильм, что взять…) — в одну строку для проверки
export const extrasText = (extras: unknown): string =>
  extras && typeof extras === 'object' ? Object.values(extras as Record<string, unknown>).map((v) => (Array.isArray(v) ? v.join(' ') : String(v ?? ''))).join(' ') : '';
